def for_indicator(ind):
    g = GROUP.get(ind.get("l1") or ind["group"], GROUP["增长"])
    if ind.get("l2") in ("利率", "政策"):
        g = RATE_GROUP
    sign = dict(g["sign"])
    for k, v in EXTRA_SIGN.get(ind["country"], {}).items():
        sign.setdefault(k, v)
    spec = IND.get(ind["id"], {})
    sign.update(spec.get("sign", {}))
    return {"logic": g["logic"], "note": spec.get("note", ""), "sign": sign, "theory": ind.get("theory", "")}
