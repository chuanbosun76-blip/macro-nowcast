def relevant(ind):
    """指标适用的机构方法（按类别映射）。"""
    ids = ["cicc"] if ind["country"] == "CN" else []
    if ind["l2"] == "总量":
        ids += ["gdpnow", "nyfed", "boe_midas", "imf"]
    elif ind["l1"] == "通胀":
        ids += ["clevfed"]
    elif ind["l1"] in ("增长", "外贸与外部", "金融", "地产", "景气") and ind["country"] == "CN":
        ids += ["cinda", "nyfed"]
    else:
        ids += ["nyfed", "boe_midas"]
    return [by_id(i) for i in dict.fromkeys(ids)]
